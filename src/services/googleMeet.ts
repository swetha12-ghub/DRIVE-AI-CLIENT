import { getAccessToken } from './firebaseAuth';

export interface MeetSpaceResult {
  meetLink: string;
  meetingCode?: string;
  calendarEventId?: string;
  calendarHtmlLink?: string;
  isLiveGoogleCreated: boolean;
  scheduledTime?: string;
}

/**
 * Creates a Google Meet space using the user's active Google OAuth access token.
 * Tries Google Meet API v2, falling back to Google Calendar API with conferenceData.
 */
export async function createGoogleMeetSpace(
  title: string = 'Task Deliverable Review Meeting',
  scheduledDate?: string,
  scheduledTime?: string
): Promise<MeetSpaceResult> {
  const token = await getAccessToken();

  if (!token) {
    // Generate a formatted Google Meet link for immediate preview / workflow
    const chars = 'abcdefghijklmnopqrstuvwxyz';
    const segment = (len: number) =>
      Array.from({ length: len }, () => chars[Math.floor(Math.random() * chars.length)]).join('');
    const code = `${segment(3)}-${segment(4)}-${segment(3)}`;
    return {
      meetLink: `https://meet.google.com/${code}`,
      meetingCode: code,
      isLiveGoogleCreated: false,
      scheduledTime: scheduledTime ? `${scheduledDate || 'Today'} at ${scheduledTime}` : undefined,
    };
  }

  // 1. Try Google Meet REST API v2
  try {
    const meetRes = await fetch('https://meet.googleapis.com/v2/spaces', {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${token}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({}),
    });

    if (meetRes.ok) {
      const data = await meetRes.json();
      const meetLink = data.meetingUri || (data.meetingCode ? `https://meet.google.com/${data.meetingCode}` : '');
      if (meetLink) {
        return {
          meetLink,
          meetingCode: data.meetingCode,
          isLiveGoogleCreated: true,
          scheduledTime: scheduledTime ? `${scheduledDate || 'Today'} at ${scheduledTime}` : undefined,
        };
      }
    } else {
      console.warn('Google Meet v2 spaces API returned status:', meetRes.status);
    }
  } catch (err) {
    console.warn('Google Meet API v2 attempt error:', err);
  }

  // 2. Try Google Calendar API with Hangouts Meet conference
  try {
    const startTime = scheduledDate && scheduledTime
      ? new Date(`${scheduledDate}T${scheduledTime}`)
      : new Date(Date.now() + 15 * 60 * 1000);
    const endTime = new Date(startTime.getTime() + 45 * 60 * 1000);

    const calRes = await fetch(
      'https://www.googleapis.com/calendar/v3/calendars/primary/events?conferenceDataVersion=1',
      {
        method: 'POST',
        headers: {
          Authorization: `Bearer ${token}`,
          'Content-Type': 'application/json',
        },
        body: JSON.stringify({
          summary: title,
          description: `AI Task Review & Deliverable Evaluation Session.\nGenerated by TaskReview AI Assistant.`,
          start: { dateTime: startTime.toISOString() },
          end: { dateTime: endTime.toISOString() },
          conferenceData: {
            createRequest: {
              requestId: `taskreview-${Date.now()}-${Math.random().toString(36).substring(2, 7)}`,
              conferenceSolutionKey: { type: 'hangoutsMeet' },
            },
          },
        }),
      }
    );

    if (calRes.ok) {
      const calData = await calRes.json();
      const meetLink =
        calData.hangoutLink ||
        calData.conferenceData?.entryPoints?.find((ep: any) => ep.entryPointType === 'video')?.uri;
      if (meetLink) {
        return {
          meetLink,
          calendarEventId: calData.id,
          calendarHtmlLink: calData.htmlLink,
          isLiveGoogleCreated: true,
          scheduledTime: startTime.toLocaleString('en-US', {
            dateStyle: 'medium',
            timeStyle: 'short',
          }),
        };
      }
    }
  } catch (calErr) {
    console.warn('Google Calendar Hangouts Meet attempt error:', calErr);
  }

  // Fallback to generated Meet code
  const chars = 'abcdefghijklmnopqrstuvwxyz';
  const segment = (len: number) =>
    Array.from({ length: len }, () => chars[Math.floor(Math.random() * chars.length)]).join('');
  const code = `${segment(3)}-${segment(4)}-${segment(3)}`;
  return {
    meetLink: `https://meet.google.com/${code}`,
    meetingCode: code,
    isLiveGoogleCreated: false,
    scheduledTime: scheduledTime ? `${scheduledDate || 'Today'} at ${scheduledTime}` : undefined,
  };
}
